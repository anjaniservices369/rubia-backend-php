<?php

namespace app\commands;

use Yii;
use yii\console\Controller;
use yii\console\ExitCode;

/**
 * Services and libraries that live in their own folder (services/<service>, libs/<lib>; see ARCHITECTURE_TARGET.md).
 *
 *   php yii service/pack --service=haltingdriver      rewrite services/haltingdriver/backend/classmap.php
 *   php yii service/pack --lib=taxicore               rewrite libs/taxicore/classmap.php
 *   php yii service/pack --customer                   rewrite customer/backend/classmap.php (the customer app)
 *   php yii service/pack --all                        every service, lib and the customer
 *   php yii service/prune --service=biketaxi [--keep=1]
 *                                                     delete older release zips (and unfinished ones) of that service
 *   php yii service/list                              what is found, with files and classes
 *   php yii service/release --service=haltingdriver [--profile=api]
 *                                                     build the service's own release zip (release/manifest.json); the
 *                                                     api profile leaves out dashboard views and front-end asset packages
 *
 * Classes keep their namespaces (app\modules\...), so nothing that uses them changed. The class map tells the autoloader
 * where they now are; it is generated from the files and must be regenerated after adding or moving a class.
 */
class ServiceController extends Controller
{
    public $service = '';
    public $lib = '';
    public $all = false;
    public $customer = false;
    public $keep = 1;
    public $profile = '';

    // [doc:start] options - Options
    public function options($actionID)
    {
        return array_merge(parent::options($actionID), ['service', 'lib', 'all', 'profile', 'customer', 'keep']);
    }
    // [doc:end] options

    private function repo()
    {
        return str_replace(chr(92), '/', dirname(Yii::getAlias('@app')));
    }

    /** @return array [base folder, folder of the class map file] */
    private function places($kind, $name)
    {
        if ($kind === 'customer') {
            $base = $this->repo() . '/customer';

            return [$base, $base . '/backend'];
        }
        $base = $this->repo() . '/' . ($kind === 'lib' ? 'libs' : 'services') . '/' . $name;

        return [$base, $kind === 'lib' ? $base : $base . '/backend'];
    }

    /** class => path relative to the class map folder */
    private function scan($kind, $name)
    {
        list($base, $mapDir) = $this->places($kind, $name);
        $map = [];
        $it = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($base, \FilesystemIterator::SKIP_DOTS));
        foreach ($it as $file) {
            $p = str_replace(chr(92), '/', (string) $file);
            if (substr($p, -4) !== '.php' || basename($p) === 'classmap.php' || strpos($p, '/views/') !== false || strpos($p, '/release/') !== false) {
                continue;
            }
            $src = (string) file_get_contents($p);
            if (preg_match('/^\s*namespace\s+([^;]+);/m', $src, $ns) && preg_match('/^\s*(?:abstract\s+|final\s+)?(?:class|trait|interface)\s+(\w+)/m', $src, $cl)) {
                $rel = strpos($p, $mapDir . '/') === 0
                    ? substr($p, strlen($mapDir) + 1)
                    : '../' . substr($p, strlen($base) + 1);
                $map[trim($ns[1]) . chr(92) . $cl[1]] = $rel;
            }
        }
        ksort($map);

        return $map;
    }

    private function write($kind, $name)
    {
        list($base, $mapDir) = $this->places($kind, $name);
        $map = $this->scan($kind, $name);
        $label = $kind === 'lib' ? "libs/$name" : ($kind === 'customer' ? 'customer' : "services/$name");
        $cmd = $kind === 'lib' ? "php yii service/pack --lib=$name" : ($kind === 'customer' ? 'php yii service/pack --customer' : "php yii service/pack --service=$name");
        $out = "<?php\n\n/**\n * Class map of the code that lives under $label.\n * Generated by `$cmd`; do not edit. Paths are relative to this folder.\n */\nreturn [\n";
        foreach ($map as $class => $rel) {
            $out .= "    '" . str_replace(chr(92), chr(92) . chr(92), $class) . "' => __DIR__ . '/" . $rel . "',\n";
        }
        $out .= "];\n";
        file_put_contents($mapDir . '/classmap.php', $out);
        $this->stdout(count($map) . " classes written to $label" . ($kind === 'lib' ? '' : '/backend') . "/classmap.php\n");
    }

    private function names($kind)
    {
        $dirs = glob($this->repo() . '/' . ($kind === 'lib' ? 'libs' : 'services') . '/*', GLOB_ONLYDIR) ?: [];

        return array_map('basename', $dirs);
    }

    // [doc:start] actionPack - Pack
    public function actionPack()
    {
        if ($this->customer) {
            $this->write('customer', 'customer');

            return ExitCode::OK;
        }
        if ($this->all) {
            if (is_dir($this->repo() . '/customer/backend')) {
                $this->write('customer', 'customer');
            }
            foreach ($this->names('lib') as $n) {
                $this->write('lib', $n);
            }
            foreach ($this->names('service') as $n) {
                if (is_dir($this->repo() . '/services/' . $n . '/backend')) {
                    $this->write('service', $n);
                }
            }

            return ExitCode::OK;
        }
        if ($this->lib !== '' && is_dir($this->repo() . '/libs/' . $this->lib)) {
            $this->write('lib', $this->lib);

            return ExitCode::OK;
        }
        if ($this->service !== '' && is_dir($this->repo() . '/services/' . $this->service)) {
            $this->write('service', $this->service);

            return ExitCode::OK;
        }
        $this->stderr("Give --service=<folder under services>, --lib=<folder under libs> or --all\n");

        return ExitCode::USAGE;
    }
    // [doc:end] actionPack

    // [doc:start] actionRelease - Builds the service's own release: services/<service>/release/dist/<service>-<date>.zip, from the manifest in.
    /**
     * Builds the service's own release: services/<service>/release/dist/<service>-<date>.zip, from the manifest in
     * services/<service>/release/manifest.json (what to include, what other services' code to leave out). The release is
     * what gets deployed for that service; other services have their own.
     */
    public function actionRelease()
    {
        $service = (string) $this->service;
        $root = $this->repo();
        $svcDir = $service === 'customer' ? $root . '/customer' : $root . '/services/' . $service;
        $manifestFile = $svcDir . '/release/manifest.json';
        if ($service === '' || !is_file($manifestFile)) {
            $this->stderr("Give a service with a release manifest: --service=haltingdriver\n");

            return ExitCode::USAGE;
        }
        if (!class_exists('ZipArchive')) {
            $this->stderr("The PHP zip extension is required.\n");

            return ExitCode::UNSPECIFIED_ERROR;
        }
        $m = json_decode((string) file_get_contents($manifestFile), true);
        $profile = (string) $this->profile;
        if ($profile !== '') {
            if (!isset($m['profiles'][$profile])) {
                $this->stderr("Unknown profile '$profile' in the manifest
");

                return ExitCode::USAGE;
            }
            $extra = $m['profiles'][$profile];
            $m['exclude'] = array_merge($m['exclude'] ?? [], $extra['exclude'] ?? []);
            $m['excludePatterns'] = array_merge($m['excludePatterns'] ?? [], $extra['excludePatterns'] ?? []);
        }
        $exclude = array_map(function ($p) {
            return rtrim($p, '/');
        }, $m['exclude'] ?? []);
        $suffixes = $m['excludeSuffixes'] ?? [];
        $patterns = $m['excludePatterns'] ?? [];
        $dist = $svcDir . '/release/dist';
        @mkdir($dist, 0775, true);
        $zipFile = $dist . '/' . $service . ($profile !== '' ? '-' . $profile : '') . '-' . date('Ymd-His') . '.zip';
        $zip = new \ZipArchive();
        $zip->open($zipFile, \ZipArchive::CREATE | \ZipArchive::OVERWRITE);
        $count = 0;
        foreach ($m['include'] as $inc) {
            $path = $root . '/' . $inc;
            if (is_file($path)) {
                $zip->addFile($path, $inc);
                $count++;
                continue;
            }
            if (!is_dir($path)) {
                continue;
            }
            $it = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($path, \FilesystemIterator::SKIP_DOTS));
            foreach ($it as $f) {
                $abs = str_replace(chr(92), '/', (string) $f);
                $rel = ltrim(substr($abs, strlen($root)), '/');
                $skip = false;
                foreach ($exclude as $e) {
                    if ($rel === $e || strpos($rel, $e . '/') === 0) {
                        $skip = true;
                        break;
                    }
                }
                foreach ($suffixes as $s) {
                    if (substr($rel, -strlen($s)) === $s) {
                        $skip = true;
                    }
                }
                foreach ($patterns as $re) {
                    if (preg_match('#' . $re . '#', $rel)) {
                        $skip = true;
                        break;
                    }
                }
                if ($skip || !is_file($abs)) {
                    continue;
                }
                $zip->addFile($abs, $rel);
                $count++;
            }
        }
        foreach ($m['emptyDirs'] ?? [] as $d) {
            $zip->addEmptyDir($d);
        }
        $zip->addFromString('RELEASE.txt', 'service: ' . $service . "\nbuilt: " . date('c') . "\nfiles: " . $count . "\n");
        $zip->close();
        $this->stdout("$count files -> " . $zipFile . ' (' . round(filesize($zipFile) / 1048576, 1) . ' MB, sha256 ' . hash_file('sha256', $zipFile) . ")\n");

        return ExitCode::OK;
    }
    // [doc:end] actionRelease

    // [doc:start] actionPrune - Deletes the older release zips of a service, keeping the newest --keep of each kind (full, api), and any zip that.
    /**
     * Deletes the older release zips of a service, keeping the newest --keep of each kind (full, api), and any zip that
     * was never finished (`*.zip.<random>`). Only files inside the service's own release/dist folder are touched.
     */
    public function actionPrune()
    {
        $service = (string) $this->service;
        $dir = $service === 'customer'
            ? $this->repo() . '/customer/release/dist'
            : $this->repo() . '/services/' . $service . '/release/dist';
        if ($service === '' || !preg_match('/^[a-z0-9]+$/', $service) || !is_dir($dir)) {
            $this->stderr("Give a service that has release/dist: --service=biketaxi\n");

            return ExitCode::USAGE;
        }
        $keep = max(0, (int) $this->keep);
        // zips built under a name the service used to have (the customer app was `customer`) count as older ones
        $names = $service === 'customer' ? '(?:customer|customer)' : $service;
        $groups = [];
        $removed = 0;
        foreach (scandir($dir) as $f) {
            if ($f === '.' || $f === '..') {
                continue;
            }
            if (preg_match('/^' . $names . '(-[a-z]+)?-\d{8}-\d{6}\.zip$/', $f, $m)) {
                $groups[$m[1] ?? ''][] = $f;
            } elseif (preg_match('/^' . $names . '.*\.zip\.[0-9a-f]+$/', $f)) {
                if (@unlink($dir . '/' . $f)) {
                    $removed++;
                    $this->stdout("removed unfinished $f\n");
                }
            }
        }
        foreach ($groups as $kind => $files) {
            rsort($files);                          // newest first: the date is in the name
            foreach (array_slice($files, $keep) as $f) {
                if (@unlink($dir . '/' . $f)) {
                    $removed++;
                    $this->stdout("removed $f\n");
                }
            }
        }
        $this->stdout("$removed file(s) removed from $dir; kept the newest $keep of each kind\n");

        return ExitCode::OK;
    }
    // [doc:end] actionPrune

    // [doc:start] actionList - List
    public function actionList()
    {
        if (is_dir($this->repo() . '/customer')) {
            list($base) = $this->places('customer', 'customer');
            $n = 0;
            foreach (new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($base, \FilesystemIterator::SKIP_DOTS)) as $f) {
                $n++;
            }
            $this->stdout(sprintf("%-8s %-16s %5d files, %3d classes\n", 'customer', 'customer', $n, count($this->scan('customer', 'customer'))));
        }
        foreach (['lib', 'service'] as $kind) {
            foreach ($this->names($kind) as $name) {
                list($base) = $this->places($kind, $name);
                $n = 0;
                $it = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($base, \FilesystemIterator::SKIP_DOTS));
                foreach ($it as $f) {
                    $n++;
                }
                $this->stdout(sprintf("%-8s %-16s %5d files, %3d classes\n", $kind, $name, $n, count($this->scan($kind, $name))));
            }
        }

        return ExitCode::OK;
    }
    // [doc:end] actionList
}
