<?php

namespace app\commands;

use Yii;
use yii\console\Controller;
use yii\console\ExitCode;
use yii\helpers\Inflector;

/**
 * Keeps the documentation that can be derived from the code in step with the code.
 *
 *   php yii docs/reference            write REFERENCE.md (every URL, status, role, setting, command, migration)
 *   php yii docs/check                exit code 1 when REFERENCE.md or the start/end markers are out of date
 *   php yii docs/annotate [--apply]   add/refresh the "[doc:start] / [doc:end]" markers around every action
 *
 * What is generated: everything that is a LIST (endpoints, constants, settings, commands, migrations, environment
 * variables). What is not generated: the explanations in BUSINESS_GUIDE.md and DEVELOPER_GUIDE.md - those describe
 * intent and are written by people. The one-line description of an endpoint comes from the first sentence of the
 * action's docblock, so describing an action in its docblock updates the reference and the marker together.
 *
 * Run `docs/reference` and `docs/annotate --apply` before building a release (DEPLOY.md), and `docs/check` in any
 * automated check.
 */
class DocsController extends Controller
{
    /** @var bool write the markers into the files (annotate) */
    public $apply = false;

    private $root;

    // [doc:start] options - Options
    public function options($actionID)
    {
        return array_merge(parent::options($actionID), ['apply']);
    }
    // [doc:end] options

    // [doc:start] init - Init
    public function init()
    {
        parent::init();
        $this->root = str_replace(chr(92), '/', dirname(Yii::getAlias('@app')));
    }
    // [doc:end] init

    // [doc:start] actionReference - Reference
    public function actionReference()
    {
        file_put_contents($this->referenceFile(), $this->buildReference());
        $this->stdout("written " . $this->referenceFile() . "\n");

        return ExitCode::OK;
    }
    // [doc:end] actionReference

    // [doc:start] actionCheck - Check
    public function actionCheck()
    {
        $stale = [];
        $file = $this->referenceFile();
        if (!is_file($file) || file_get_contents($file) !== $this->buildReference()) {
            $stale[] = 'REFERENCE.md (run: php yii docs/reference)';
        }
        foreach ($this->annotateAll(false) as $path => $changed) {
            if ($changed) {
                $stale[] = $path . ' (run: php yii docs/annotate --apply)';
            }
        }
        if ($stale) {
            $this->stderr("Out of date:\n  " . implode("\n  ", $stale) . "\n");

            return ExitCode::UNSPECIFIED_ERROR;
        }
        $this->stdout("documentation is up to date\n");

        return ExitCode::OK;
    }
    // [doc:end] actionCheck

    // [doc:start] actionAnnotate - Annotate
    public function actionAnnotate()
    {
        $n = 0;
        foreach ($this->annotateAll($this->apply) as $path => $changed) {
            if ($changed) {
                $n++;
                $this->stdout(($this->apply ? 'updated ' : 'would update ') . $path . "\n");
            }
        }
        $this->stdout("$n file(s) " . ($this->apply ? 'updated' : 'need updating (use --apply)') . "\n");

        return ExitCode::OK;
    }
    // [doc:end] actionAnnotate

    // ---------------------------------------------------------------------------------------------- reference

    private function referenceFile()
    {
        return $this->root . DIRECTORY_SEPARATOR . 'REFERENCE.md';
    }

    private function buildReference()
    {
        $out = [];
        $out[] = '# Reference (generated)';
        $out[] = '';
        $out[] = '> **Generated by `php yii docs/reference`. Do not edit by hand** - change the code or the docblocks and';
        $out[] = '> regenerate. Explanations live in `BUSINESS_GUIDE.md` and `DEVELOPER_GUIDE.md`.';
        $out[] = '';

        // endpoints
        $out[] = '## URLs by module';
        foreach ($this->controllers() as $c) {
            $out[] = '';
            $out[] = '### ' . $c['title'] . ' - `' . $c['file'] . '`';
            if ($c['summary'] !== '') {
                $out[] = '';
                $out[] = $c['summary'];
            }
            $out[] = '';
            $out[] = '| URL | Action | What it does |';
            $out[] = '|---|---|---|';
            foreach ($c['actions'] as $a) {
                $out[] = '| `' . $a['url'] . '` | `' . $a['name'] . '` | ' . str_replace('|', '/', $a['summary']) . ' |';
            }
        }

        // constants
        $out[] = '';
        $out[] = '## States and codes';
        foreach ([
            'Driver-service booking (`booking.status`)' => 'modules/admin/models/base/Booking.php',
            'Driver offer (`driver_requests.status`)' => 'modules/admin/models/base/DriverRequests.php',
            'Taxi ride (`ride_request.status`)' => 'modules/admin/models/base/RideRequest.php',
            'Account (`user.status`, `user.user_role`)' => 'models/User.php',
        ] as $title => $file) {
            $out[] = '';
            $out[] = '### ' . $title;
            $out[] = '';
            $out[] = '| Constant | Value |';
            $out[] = '|---|---|';
            foreach ($this->constants($file) as $name => $value) {
                $out[] = '| `' . $name . '` | ' . $value . ' |';
            }
        }

        // web settings (names only: values may be secret)
        $out[] = '';
        $out[] = '## Dashboard settings (`web_setting`)';
        $out[] = '';
        try {
            $rows = Yii::$app->db->createCommand('SELECT setting_key, name FROM web_setting ORDER BY type_id, setting_key')->queryAll();
            $out[] = '| Key | Label |';
            $out[] = '|---|---|';
            foreach ($rows as $r) {
                $out[] = '| `' . $r['setting_key'] . '` | ' . $r['name'] . ' |';
            }
        } catch (\Throwable $e) {
            $out[] = '_database not reachable when this was generated_';
        }

        // console
        $out[] = '';
        $out[] = '## Console commands (`php yii ...`)';
        $out[] = '';
        $out[] = '| Command | What it does |';
        $out[] = '|---|---|';
        foreach (glob($this->root . '/app/commands/*Controller.php') as $f) {
            $id = Inflector::camel2id(basename($f, 'Controller.php'));
            foreach ($this->methods($f) as $m) {
                if (strpos($m['name'], 'action') === 0 && $m['name'] !== 'actions') {
                    $out[] = '| `php yii ' . $id . '/' . Inflector::camel2id(substr($m['name'], 6)) . '` | ' . ($m['summary'] !== '' ? $m['summary'] : Inflector::camel2words(substr($m['name'], 6)) . '.') . ' |';
                }
            }
        }

        // migrations
        $out[] = '';
        $out[] = '## Database scripts (`app/database/migrations`)';
        $out[] = '';
        foreach (glob($this->root . '/app/database/migrations/*.up.sql') as $f) {
            $out[] = '- `' . basename($f, '.up.sql') . '`';
        }

        // environment
        $out[] = '';
        $out[] = '## Environment variables read by the code';
        $out[] = '';
        $vars = [];
        foreach (['config', 'modules', 'components', 'commands', 'models'] as $dir) {
            if (!is_dir($this->root . '/app/' . $dir)) {
                continue;
            }
            $it = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($this->root . '/app/' . $dir, \FilesystemIterator::SKIP_DOTS));
            foreach ($this->withServices($it, $dir) as $f) {
                if ($f->getExtension() === 'php' && !preg_match('/\.bak/', $f->getFilename())) {
                    if (preg_match_all("/getenv\s*\(\s*'([A-Z][A-Z0-9_]+)'/", file_get_contents($f->getPathname()), $m)) {
                        foreach ($m[1] as $v) {
                            $vars[$v] = true;
                        }
                    }
                }
            }
        }
        ksort($vars);
        foreach (array_keys($vars) as $v) {
            $out[] = '- `' . $v . '`';
        }

        return implode("\n", $out) . "\n";
    }

    /**
     * Every controller of every module with its actions, public URL and summary.
     */
    private function controllers()
    {
        $apiPrefix = [];
        foreach ((require Yii::getAlias('@app/config/api-routes.php')) as $pattern => $route) {
            if (preg_match('#^api/([\w-]+)$#', $pattern, $m)) {
                $apiPrefix[preg_replace('#/index$#', '', $route)] = $m[1];
            }
        }
        $result = [];
        $base = $this->root . '/app/modules';
        foreach ($this->controllerFiles() as $file) {
            $moduleDir = $this->moduleDirOf($file);
            $moduleId = $this->moduleId($moduleDir);
            $controllerId = Inflector::camel2id(basename($file, 'Controller.php'));
            $route = $moduleId . '/' . $controllerId;
            // the service's own customer-side module answers the addresses the user app module shares with it
            $routeKey = strpos($route, 'haltingdriver-customer/') === 0 ? 'customer-app/' . substr($route, strlen('haltingdriver-customer/')) : $route;
            $methods = $this->methods($file);
            $actions = [];
            foreach ($methods as $m) {
                if (strpos($m['name'], 'action') !== 0 || $m['name'] === 'actions') {
                    continue;
                }
                $actionId = Inflector::camel2id(substr($m['name'], 6));
                $url = isset($apiPrefix[$routeKey])
                    ? '/api/' . $apiPrefix[$routeKey] . '/' . $actionId
                    : '/' . $moduleId . '/' . $controllerId . '/' . $actionId;
                $actions[] = ['url' => $url, 'name' => $m['name'], 'summary' => $m['summary'] !== '' ? $m['summary'] : Inflector::camel2words(substr($m['name'], 6)) . '.'];
            }
            if (!$actions) {
                continue;
            }
            $result[] = [
                'title' => $moduleId . ' / ' . $controllerId,
                'file' => $this->relative($file),
                'summary' => $this->classSummary($file),
                'actions' => $actions,
            ];
        }
        usort($result, function ($a, $b) {
            return strcmp($a['title'], $b['title']);
        });

        return $result;
    }

    /** Every controller file: those of the app modules and those that live in a service folder. */
    private function controllerFiles()
    {
        return array_merge(
            glob($this->root . '/app/modules/*/controllers/*Controller.php'),
            glob($this->root . '/services/*/backend/modules/*/controllers/*Controller.php'),
            glob($this->root . '/services/*/partner-dashboard/controllers/*Controller.php'),
            glob($this->root . '/libs/*/dashboard/controllers/*Controller.php'),
            glob($this->root . '/services/*/backend/modules/*/controllers/*Controller.php'),
            glob($this->root . '/services/*/customer-backend/controllers/*Controller.php'),
            glob($this->root . '/libs/*/modules/*/controllers/*Controller.php'),
            glob($this->root . '/libs/*/backend/*/controllers/*Controller.php'),
            glob($this->root . '/customer/backend/modules/*/controllers/*Controller.php'),
            glob($this->root . '/customer/dashboard/controllers/*Controller.php')
        );
    }

    /** Module folder of a controller file (partner-dashboard controllers belong to the admin module). */
    private function moduleDirOf($file)
    {
        $file = str_replace(chr(92), '/', $file);
        if (preg_match('#/(partner-dashboard|dashboard)/controllers/#', $file) || strpos($file, '/customer/dashboard/controllers/') !== false) {
            return 'admin';
        }
        if (preg_match('#/customer-backend/controllers/#', $file)) {
            return 'haltingdriver-customer';
        }
        if (preg_match('#/libs/taxicore/backend/(partner|rider)/controllers/#', $file, $m)) {
            return 'taxicore-' . $m[1];
        }

        return basename(dirname(dirname($file)));
    }

    /** Path of a file relative to the repository root. */
    private function relative($file)
    {
        return ltrim(str_replace($this->root, '', str_replace(chr(92), '/', $file)), '/');
    }

    /** A path relative to app/ ('modules/admin/models/base/Booking.php'): where the file is today, also after it moved to services/. */
    private function locate($rel)
    {
        $app = $this->root . '/app/' . $rel;
        if (is_file($app)) {
            return $app;
        }
        if (strpos($rel, 'modules/admin/models/') === 0) {
            $tail = substr($rel, strlen('modules/admin/'));
            foreach (array_merge(glob($this->root . '/services/*/backend/' . $tail) ?: [], glob($this->root . '/libs/*/' . $tail) ?: [], glob($this->root . '/customer/' . $tail) ?: []) as $f) {
                return $f;
            }
        }
        if (strpos($rel, 'models/') === 0) {
            foreach (glob($this->root . '/libs/*/appmodels/' . substr($rel, strlen('models/'))) ?: [] as $f) {
                return $f;
            }
        }

        return $app;
    }

    /** Files of an app folder, plus (for modules) every file of the service folders. */
    private function withServices($iterator, $dir)
    {
        $all = iterator_to_array($iterator, false);
        $extra = [];
        foreach (array_merge(glob($this->root . '/services/*', GLOB_ONLYDIR), glob($this->root . '/libs/*', GLOB_ONLYDIR), glob($this->root . '/customer', GLOB_ONLYDIR)) as $svc) {
            $it = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($svc, \FilesystemIterator::SKIP_DOTS));
            foreach ($it as $f) {
                $extra[] = $f;
            }
        }

        return $dir === 'modules' ? array_merge($all, $extra) : $all;
    }

    /** module folder -> module id, from the registered modules. */
    private function moduleId($folder)
    {
        static $map = null;
        if ($map === null) {
            // The console application does not register the web modules, so read them from the web config.
            $map = [];
            $web = require Yii::getAlias('@app/config/web.php');
            foreach (($web['modules'] ?? []) as $id => $def) {
                $class = is_array($def) ? ($def['class'] ?? '') : (string) $def;
                if (preg_match('/modules.([A-Za-z0-9_]+).[A-Za-z0-9_]+$/', $class, $m)) {
                    $map[$m[1]] = $id;
                }
            }
        }

        return $map[$folder] ?? $folder;
    }

    private function constants($relativeFile)
    {
        $src = file_get_contents($this->locate($relativeFile));
        $out = [];
        if (preg_match_all('/^\s*(?:public\s+)?const\s+([A-Za-z_][A-Za-z0-9_]*)\s*=\s*([^;]+);/m', $src, $m, PREG_SET_ORDER)) {
            foreach ($m as $c) {
                if (preg_match('/^(STATUS_|ROLE_|RIDER_TYPE_|TRIP_TYPE_|PAYMENT_|payment_|online_status|CAR_TYPE_)/', $c[1])) {
                    $out[$c[1]] = trim($c[2]);
                }
            }
        }

        return $out;
    }

    // ------------------------------------------------------------------------------------------- annotation

    /**
     * @return array [relative path => changed?]
     */
    private function annotateAll($apply)
    {
        $files = array_merge(
            $this->controllerFiles(),
            glob($this->root . '/app/modules/*/services/*.php'),
            glob($this->root . '/libs/*/modules/*/services/*.php'),
            glob($this->root . '/customer/backend/modules/*/services/*.php'),
            glob($this->root . '/services/*/backend/dispatch/*.php'),
            glob($this->root . '/app/commands/*Controller.php')
        );
        $result = [];
        foreach ($files as $file) {
            $result[str_replace($this->root . '/', '', str_replace('\\', '/', $file))] = $this->annotateFile($file, $apply);
        }

        return $result;
    }

    private function annotateFile($file, $apply)
    {
        $src = file_get_contents($file);
        $eol = strpos($src, "\r\n") !== false ? "\r\n" : "\n";
        $lines = preg_split('/\r\n|\n/', $src);

        // 1. drop the markers written earlier
        $clean = [];
        foreach ($lines as $line) {
            if (preg_match('/^\s*\/\/ \[doc:(start|end)\]/', $line)) {
                continue;
            }
            $clean[] = $line;
        }
        $methods = $this->methodsFromSource(implode($eol, $clean));

        // 2. insert from the bottom so earlier line numbers stay valid
        usort($methods, function ($a, $b) {
            return $b['endLine'] <=> $a['endLine'];
        });
        $route = $this->routeFor($file);
        foreach ($methods as $m) {
            if (!preg_match('/^(action|assign|expire|run|send|notify|cancel|reopen|setProgress)/', $m['name']) && !$m['public']) {
                continue;
            }
            $indent = $m['indent'];
            $what = $m['summary'] !== '' ? $m['summary'] : preg_replace('/^Action /', '', Inflector::camel2words($m['name']));
            $where = '';
            if (strpos($m['name'], 'action') === 0 && $m['name'] !== 'actions') {
                $where = $route ? ' - ' . $this->urlFor($route, $m['name']) : '';
            }
            array_splice($clean, $m['endLine'], 0, [$indent . '// [doc:end] ' . $m['name']]);
            array_splice($clean, $m['startLine'] - 1, 0, [$indent . '// [doc:start] ' . $m['name'] . $where . ' - ' . $what]);
        }
        $new = implode($eol, $clean);
        $changed = $new !== $src;
        if ($changed && $apply) {
            file_put_contents($file, $new);
        }

        return $changed;
    }

    private function routeFor($file)
    {
        $file = str_replace('\\', '/', $file);
        if (preg_match('#(?:services/[A-Za-z0-9_]+/partner-dashboard|libs/[A-Za-z0-9_]+/dashboard|customer/dashboard)/controllers/(\w+)Controller\.php$#', $file, $m)) {
            return $this->moduleId('admin') . '/' . Inflector::camel2id($m[1]);
        }
        if (!preg_match('#modules/([A-Za-z0-9_]+)/controllers/(\w+)Controller\.php$#', $file, $m)) {
            return null;
        }

        return $this->moduleId($m[1]) . '/' . Inflector::camel2id($m[2]);
    }

    private function urlFor($route, $method)
    {
        static $apiPrefix = null;
        if ($apiPrefix === null) {
            $apiPrefix = [];
            foreach ((require Yii::getAlias('@app/config/api-routes.php')) as $pattern => $r) {
                if (preg_match('#^api/([\w-]+)$#', $pattern, $m)) {
                    $apiPrefix[preg_replace('#/index$#', '', $r)] = $m[1];
                }
            }
        }
        $action = Inflector::camel2id(substr($method, 6));

        return isset($apiPrefix[$route]) ? '/api/' . $apiPrefix[$route] . '/' . $action : '/' . $route . '/' . $action;
    }

    // --------------------------------------------------------------------------------------------- parsing

    private function methods($file)
    {
        return $this->methodsFromSource(file_get_contents($file));
    }

    private function classSummary($file)
    {
        $src = file_get_contents($file);
        if (preg_match('/\/\*\*(.*?)\*\/\s*(?:abstract\s+|final\s+)?class\s/s', $src, $m)) {
            $text = preg_replace('/^\s*\* ?/m', '', $m[1]);
            $first = trim(preg_split('/\n\s*\n/', trim($text))[0] ?? '');

            return preg_replace('/\s+/', ' ', $first);
        }

        return '';
    }

    /**
     * Methods of the classes in a PHP source with start/end line, docblock summary and indentation.
     * startLine is the first line of the method's docblock (or of the method when it has none).
     */
    private function methodsFromSource($src)
    {
        $tokens = token_get_all($src);
        $n = count($tokens);
        $lineAt = [];
        $ln = 1;
        foreach ($tokens as $idx => $tk) {
            $lineAt[$idx] = $ln;
            $ln += substr_count(is_array($tk) ? $tk[1] : $tk, chr(10));
        }
        $methods = [];
        $lastDoc = null;
        $lastDocLine = null;
        $visibility = 'public';
        $classDepth = [];
        $depth = 0;
        for ($i = 0; $i < $n; $i++) {
            $t = $tokens[$i];
            if (is_array($t)) {
                if ($t[0] === T_DOC_COMMENT) {
                    $lastDoc = $t[1];
                    $lastDocLine = $t[2];
                } elseif ($t[0] === T_PUBLIC || $t[0] === T_PRIVATE || $t[0] === T_PROTECTED) {
                    $visibility = strtolower($t[1]);
                } elseif ($t[0] === T_CLASS) {
                    $classDepth[] = $depth;
                } elseif ($t[0] === T_FUNCTION && $classDepth && $depth === end($classDepth) + 1) {
                    // method name
                    $j = $i + 1;
                    while ($j < $n && !(is_array($tokens[$j]) && $tokens[$j][0] === T_STRING)) {
                        if ($tokens[$j] === '(') {
                            break; // closure
                        }
                        $j++;
                    }
                    if ($j >= $n || !is_array($tokens[$j])) {
                        continue;
                    }
                    $name = $tokens[$j][1];
                    $declLine = $t[2];
                    // body
                    $k = $j;
                    while ($k < $n && $tokens[$k] !== '{' && $tokens[$k] !== ';') {
                        $k++;
                    }
                    if ($k >= $n || $tokens[$k] === ';') {
                        $lastDoc = null;
                        continue; // abstract / interface
                    }
                    $d = 0;
                    $endLine = $declLine;
                    for ($p = $k; $p < $n; $p++) {
                        $tk = $tokens[$p];
                        $txt = is_array($tk) ? $tk[1] : $tk;
                        if (is_array($tk) && ($tk[0] === T_CURLY_OPEN || $tk[0] === T_DOLLAR_OPEN_CURLY_BRACES)) {
                            $d++;
                        } elseif ($txt === '{') {
                            $d++;
                        } elseif ($txt === '}') {
                            $d--;
                            if ($d === 0) {
                                $endLine = $lineAt[$p];
                                break;
                            }
                        }
                    }
                    // first line of the declaration including modifiers
                    $startLine = $declLine;
                    for ($b = $i - 1; $b >= 0 && $b >= $i - 8; $b--) {
                        $bt = $tokens[$b];
                        if (is_array($bt) && in_array($bt[0], [T_PUBLIC, T_PRIVATE, T_PROTECTED, T_STATIC, T_FINAL, T_ABSTRACT], true)) {
                            $startLine = min($startLine, $bt[2]);
                        } elseif (is_array($bt) && in_array($bt[0], [T_WHITESPACE], true)) {
                            continue;
                        } else {
                            break;
                        }
                    }
                    $summary = '';
                    if ($lastDoc !== null && $lastDocLine !== null && $lastDocLine < $startLine && ($startLine - $this->docEndLine($lastDoc, $lastDocLine)) <= 2) {
                        $summary = $this->docSummary($lastDoc);
                        $startLine = $lastDocLine;
                    }
                    $srcLines = preg_split('/\r\n|\n/', $src);
                    $declText = $srcLines[$declLine - 1] ?? '';
                    preg_match('/^(\s*)/', $declText, $im);
                    $methods[] = [
                        'name' => $name,
                        'startLine' => $startLine,
                        'endLine' => $endLine,
                        'summary' => $summary,
                        'public' => $visibility === 'public',
                        'indent' => $im[1] ?? '    ',
                    ];
                    $lastDoc = null;
                    $visibility = 'public';
                }
            } else {
                if ($t === '{') {
                    $depth++;
                } elseif ($t === '}') {
                    $depth--;
                    if ($classDepth && $depth === end($classDepth)) {
                        array_pop($classDepth);
                    }
                }
                if ($t === ';') {
                    $lastDoc = null;
                }
            }
            if (is_array($t) && ($t[0] === T_CURLY_OPEN || $t[0] === T_DOLLAR_OPEN_CURLY_BRACES)) {
                $depth++;
            }
        }

        return $methods;
    }

    private function docEndLine($doc, $startLine)
    {
        return $startLine + substr_count($doc, "\n");
    }

    private function docSummary($doc)
    {
        $text = preg_replace('/^\s*\/\*\*|\*\/\s*$/', '', $doc);
        $text = preg_replace('/^\s*\* ?/m', '', $text);
        foreach (preg_split('/\n/', trim($text)) as $line) {
            $line = trim($line);
            if ($line !== '' && $line[0] !== '@') {
                return preg_replace('/\s+/', ' ', rtrim($line, '. ')) . '.';
            }
        }

        return '';
    }
}
